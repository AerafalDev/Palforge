using System.Text;

namespace Palforge.Unreal.Sdk;

internal static class SdkEmitter
{
    private const string Indent = "    ";
    private const string Body = Indent + Indent;
    private const string DataTableClass = "DataTable";
    private const string Header = "// <auto-generated/>\n#nullable enable\n";

    public static string Emit(SdkEnum enumeration)
    {
        var builder = new StringBuilder();

        builder.Append(Header);
        builder.Append("namespace ").Append(enumeration.Namespace).Append(';').Append('\n').Append('\n');
        builder.Append("public enum ").Append(enumeration.Name);

        if (enumeration.Underlying is not "int")
            builder.Append(" : ").Append(enumeration.Underlying);

        builder.Append('\n').Append('{').Append('\n');

        for (var index = 0; index < enumeration.Members.Count; index++)
        {
            var member = enumeration.Members[index];

            builder.Append(Indent).Append(member.Name).Append(" = ").Append(member.Value);
            builder.Append(index < enumeration.Members.Count - 1 ? "," : "").Append('\n');
        }

        return builder.Append('}').Append('\n').ToString();
    }

    public static string Emit(SdkClass type)
    {
        var builder = new StringBuilder();

        builder.Append(Header);
        builder.Append("using Palforge.Unreal.Reflection;").Append('\n');

        if (type.UeName is not null || type.Methods.Any(static method => method.IsStatic))
            builder.Append("using Palforge.Unreal.Sdk;").Append('\n');

        builder.Append('\n');
        builder.Append("namespace ").Append(type.Namespace).Append(';').Append('\n').Append('\n');
        builder.Append("public class ").Append(type.Name).Append(" : ").Append(type.BaseName).Append('\n').Append('{').Append('\n');

        var members = new List<Action>();

        foreach (var property in type.Properties)
            members.Add(() => EmitProperty(builder, property));

        members.Add(() => EmitConstructor(builder, type));

        if (type.UeName is { } ueName)
        {
            if (type.IsStruct)
                members.Add(() => EmitAllocate(builder, type, ueName));
            else
            {
                var hidesBase = type.BaseName is not "UObject";
                members.Add(() => EmitStaticClass(builder, ueName, hidesBase));
                members.Add(() => EmitFactory(builder, type, ueName, hidesBase));
                members.Add(() => EmitLoad(builder, type, hidesBase));

                if (ueName is DataTableClass)
                    members.Add(() => EmitRows(builder));
            }
        }

        foreach (var method in type.Methods)
            members.Add(() => EmitMethod(builder, method));

        for (var index = 0; index < members.Count; index++)
        {
            if (index > 0)
                builder.Append('\n');

            members[index]();
        }

        return builder.Append('}').Append('\n').ToString();
    }

    private static void EmitConstructor(StringBuilder builder, SdkClass type)
    {
        var baseCall = type is { IsStruct: true, UeName: { } ueName } ? $"base(address, context, \"{ueName}\")" : "base(address, context)";

        builder.Append(Indent).Append("internal ").Append(type.Name).Append("(nint address, UnrealContext context) : ").Append(baseCall).Append('\n');
        builder.Append(Indent).Append('{').Append('\n').Append(Indent).Append('}').Append('\n');

        if (type.IsStruct)
        {
            builder.Append('\n');
            builder.Append(Indent).Append("private protected ").Append(type.Name).Append("(nint address, UnrealContext context, string? structName) : base(address, context, structName)").Append('\n');
            builder.Append(Indent).Append('{').Append('\n').Append(Indent).Append('}').Append('\n');
        }
    }

    private static void EmitStaticClass(StringBuilder builder, string ueName, bool hidesBase)
    {
        builder.Append(Indent).Append("public static ").Append(hidesBase ? "new " : "").Append("UClass? StaticClass()").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.StaticClass(\"").Append(ueName).Append("\");").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitFactory(StringBuilder builder, SdkClass type, string ueName, bool hidesBase)
    {
        var modifier = hidesBase ? "new " : "";
        var (method, parameter, call) = type.IsActor
            ? ("Spawn", "UObject? owner = null, UStructValue? at = null", $"SdkEnv.SpawnActor(\"{ueName}\", owner, at)")
            : ("New", "UObject? outer = null", $"SdkEnv.New(\"{ueName}\", outer)");

        builder.Append(Indent).Append("public static ").Append(modifier).Append(type.Name).Append("? ").Append(method).Append('(').Append(parameter).Append(')').Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return ").Append(call).Append(" as ").Append(type.Name).Append(';').Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitRows(StringBuilder builder)
    {
        builder.Append(Indent).Append("public UScriptStruct? RowType =>").Append('\n');
        builder.Append(Body).Append("SdkEnv.RowType(this);").Append('\n');

        builder.Append('\n');
        builder.Append(Indent).Append("public System.Collections.Generic.IEnumerable<System.Collections.Generic.KeyValuePair<string, UStructValue>> Rows()").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.Rows(this);").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');

        builder.Append('\n');
        builder.Append(Indent).Append("public UStructValue? Row(string rowName)").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.Row(this, rowName);").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');

        builder.Append('\n');
        builder.Append(Indent).Append("public System.Collections.Generic.IEnumerable<System.Collections.Generic.KeyValuePair<string, T>> Rows<T>() where T : UStructValue").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.Rows<T>(this);").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');

        builder.Append('\n');
        builder.Append(Indent).Append("public T? Row<T>(string rowName) where T : UStructValue").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.Row(this, rowName) as T;").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitLoad(StringBuilder builder, SdkClass type, bool hidesBase)
    {
        builder.Append(Indent).Append("public static ").Append(hidesBase ? "new " : "").Append(type.Name).Append("? Load(string path)").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.LoadAsset(path) as ").Append(type.Name).Append(';').Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitAllocate(StringBuilder builder, SdkClass type, string ueName)
    {
        var hidesBase = type.BaseName is not "UStructValue";

        builder.Append(Indent).Append("public static ").Append(hidesBase ? "new " : "").Append(type.Name).Append("? Allocate()").Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Body).Append("return SdkEnv.AllocateStruct<").Append(type.Name).Append(">(\"").Append(ueName).Append("\");").Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitMethod(StringBuilder builder, SdkMethod method)
    {
        var signature = string.Join(", ", method.Parameters.Select(static parameter => $"{Modifier(parameter)}{parameter.TypeName} {parameter.Name}"));

        var returnType = method.ReturnStruct is null ? method.ReturnType : method.ReturnType + "?";

        builder.Append(Indent).Append("public ").Append(method.IsStatic ? "static " : "").Append(returnType).Append(' ').Append(method.Name).Append('(').Append(signature).Append(')').Append('\n');
        builder.Append(Indent).Append('{').Append('\n');

        if (method.ReturnStruct is not null)
            EmitStructCall(builder, method);
        else if (method.Parameters.Any(static parameter => parameter.Output is not null || parameter.Destination is not null))
            EmitCallWithOutputs(builder, method);
        else
            EmitPlainCall(builder, method);

        builder.Append(Indent).Append('}').Append('\n');
    }

    private static void EmitPlainCall(StringBuilder builder, SdkMethod method)
    {
        var arguments = string.Join("", method.Parameters.Select(static parameter => ", " + parameter.Marshal));

        var call = method.IsStatic
            ? $"SdkEnv.CallStatic(\"{method.OwnerUeName}\", \"{method.UeName}\"{arguments})"
            : $"Call(\"{method.UeName}\"{arguments})";

        if (method.ReturnReader is { } reader)
            builder.Append(Body).Append("return ").Append(reader.Replace(SdkMethodMap.CallPlaceholder, call)).Append(';').Append('\n');
        else
            builder.Append(Body).Append(call).Append(';').Append('\n');
    }

    private static void EmitStructCall(StringBuilder builder, SdkMethod method)
    {
        var reads = method.Parameters.Where(static parameter => parameter.Output is not null).ToArray();

        if (reads.Length is 0)
        {
            var inlined = string.Join("", method.Parameters.Select(static parameter => ", " + parameter.Marshal));

            builder.Append(Body).Append("return ").Append(StructCall(method, inlined)).Append(';').Append('\n');

            return;
        }

        var arguments = string.Join(", ", method.Parameters.Select(static parameter => parameter.Marshal));

        builder.Append(Body).Append("var arguments = new byte[][] { ").Append(arguments).Append(" };").Append('\n');
        builder.Append(Body).Append("var result = ").Append(StructCall(method, ", arguments, out var outputs")).Append(';').Append('\n');

        for (var index = 0; index < method.Parameters.Count; index++)
        {
            if (method.Parameters[index].Output is { } output)
                builder.Append(Body).Append(method.Parameters[index].Name).Append(" = ").Append(output.Replace(SdkMethodMap.CallPlaceholder, $"outputs[{index}]")).Append(';').Append('\n');
        }

        builder.Append(Body).Append("return result;").Append('\n');
    }

    private static string StructCall(SdkMethod method, string tail)
    {
        return method.IsStatic
            ? $"SdkEnv.CallStaticForStruct<{method.ReturnType}>(\"{method.OwnerUeName}\", \"{method.UeName}\", \"{method.ReturnStruct}\"{tail})"
            : $"SdkEnv.CallForStruct<{method.ReturnType}>(this, \"{method.UeName}\", \"{method.ReturnStruct}\"{tail})";
    }

    private static void EmitCallWithOutputs(StringBuilder builder, SdkMethod method)
    {
        var arguments = string.Join(", ", method.Parameters.Select(static parameter => parameter.Marshal));

        var filled = method.Parameters.Any(static parameter => parameter.Destination is not null);
        var passed = filled ? "arguments, destinations, out var outputs" : "arguments, out var outputs";

        var call = method.IsStatic
            ? $"SdkEnv.CallStatic(\"{method.OwnerUeName}\", \"{method.UeName}\", {passed})"
            : $"Call(\"{method.UeName}\", {passed})";

        builder.Append(Body).Append("var arguments = new byte[][] { ").Append(arguments).Append(" };").Append('\n');

        if (filled)
        {
            var destinations = string.Join(", ", method.Parameters.Select(static parameter => parameter.Destination ?? "0"));

            builder.Append(Body).Append("var destinations = new nint[] { ").Append(destinations).Append(" };").Append('\n');
        }

        builder.Append(Body).Append(method.ReturnReader is null ? "" : "var result = ").Append(call).Append(';').Append('\n');

        for (var index = 0; index < method.Parameters.Count; index++)
        {
            if (method.Parameters[index].Output is { } output)
                builder.Append(Body).Append(method.Parameters[index].Name).Append(" = ").Append(output.Replace(SdkMethodMap.CallPlaceholder, $"outputs[{index}]")).Append(';').Append('\n');
        }

        if (method.ReturnReader is { } reader)
            builder.Append(Body).Append("return ").Append(reader.Replace(SdkMethodMap.CallPlaceholder, "result")).Append(';').Append('\n');
    }

    private static string Modifier(SdkParameter parameter)
    {
        return parameter.Modifier.Length is 0 ? "" : parameter.Modifier + " ";
    }

    public static string EmitRegistry(IReadOnlyList<(string UeName, string CsName)> factories, IReadOnlyList<(string UeName, string CsName)> structs)
    {
        var builder = new StringBuilder();

        builder.Append(Header);
        builder.Append("using Palforge.Unreal;").Append('\n');
        builder.Append("using Palforge.Unreal.Sdk;").Append('\n').Append('\n');
        builder.Append("namespace Palforge.Sdk;").Append('\n').Append('\n');
        builder.Append("internal static class SdkRegistry").Append('\n').Append('{').Append('\n');
        builder.Append(Indent).Append("internal static void Register(UnrealRuntime runtime)").Append('\n').Append(Indent).Append('{').Append('\n');
        builder.Append(Indent).Append(Indent).Append("var context = runtime.Reflection;").Append('\n');
        builder.Append(Indent).Append(Indent).Append("SdkEnv.Context = context;").Append('\n');

        foreach (var (ueName, csName) in factories)
            builder.Append(Indent).Append(Indent).Append("context.RegisterSdkFactory(\"").Append(ueName).Append("\", typeof(").Append(csName).Append("), static (address, reflection) => new ").Append(csName).Append("(address, reflection));").Append('\n');

        foreach (var (ueName, csName) in structs)
            builder.Append(Indent).Append(Indent).Append("context.RegisterSdkStruct(\"").Append(ueName).Append("\", static (address, reflection) => new ").Append(csName).Append("(address, reflection));").Append('\n');

        return builder.Append(Indent).Append('}').Append('\n').Append('}').Append('\n').ToString();
    }

    private static void EmitProperty(StringBuilder builder, SdkProperty property)
    {
        if (property.SetBody is not { } setBody)
        {
            builder.Append(Indent).Append("public ").Append(property.TypeName).Append(' ').Append(property.Name).Append(" =>").Append('\n');
            builder.Append(Indent).Append(Indent).Append(property.GetBody).Append(';').Append('\n');
            return;
        }

        builder.Append(Indent).Append("public ").Append(property.TypeName).Append(' ').Append(property.Name).Append('\n');
        builder.Append(Indent).Append('{').Append('\n');
        builder.Append(Indent).Append(Indent).Append("get => ").Append(property.GetBody).Append(';').Append('\n');
        builder.Append(Indent).Append(Indent).Append("set => ").Append(setBody).Append(';').Append('\n');
        builder.Append(Indent).Append('}').Append('\n');
    }
}