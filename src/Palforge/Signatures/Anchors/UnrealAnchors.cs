    private static bool IsPlausibleObjectArray(AnchorContext context)
    {
        if (!context.IsInWritableSection())
            return false;

        return context.Memory.IsReadable(context.Address, 64);
    }

    private static bool IsPlausiblePointer(AnchorContext context)
    {
        if (!context.IsInWritableSection())
            return false;

        return context.Memory.TryRead(context.Address, out nint _);
    }

    private static bool IsPlausibleFunction(AnchorContext context)
    {
        if (!context.IsInExecutableSection())
            return false;

        return context.Memory.IsReadable(context.Address, 16);
    }
